    private static void appendIntegerParser(StringBuilder asm) {
        asm.append("__scanner_parse_signed:\n")
                .append("    call __scanner_read_token\n")
                .append("    mov r10, rax\n")
                .append("    test r10, r10\n")
                .append("    jz __scanner_input_error\n")
                .append("    lea rsi, [rel __scanner_token]\n")
                .append("    xor r9d, r9d\n")
                .append("    xor r8d, r8d\n")
                .append("    mov al, byte [rsi]\n")
                .append("    cmp al, '-'\n")
                .append("    jne .scanner_signed_check_plus\n")
                .append("    mov r8d, 1\n")
                .append("    inc r9\n")
                .append("    jmp .scanner_signed_start_digits\n")
                .append(".scanner_signed_check_plus:\n")
                .append("    cmp al, '+'\n")
                .append("    jne .scanner_signed_start_digits\n")
                .append("    inc r9\n")
                .append(".scanner_signed_start_digits:\n")
                .append("    cmp r9, r10\n")
                .append("    jae __scanner_input_error\n")
                .append("    xor eax, eax\n")
                .append(".scanner_signed_loop:\n")
                .append("    cmp r9, r10\n")
                .append("    jae .scanner_signed_done\n")
                .append("    movzx ecx, byte [rsi + r9]\n")
                .append("    sub ecx, '0'\n")
                .append("    cmp ecx, 9\n")
                .append("    ja __scanner_input_error\n")
                .append("    imul rax, rax, 10\n")
                .append("    jo __scanner_input_error\n")
                .append("    sub rax, rcx\n")
                .append("    jo __scanner_input_error\n")
                .append("    inc r9\n")
                .append("    jmp .scanner_signed_loop\n")
                .append(".scanner_signed_done:\n")
                .append("    test r8d, r8d\n")
                .append("    jnz .scanner_signed_return\n")
                .append("    neg rax\n")
                .append("    jo __scanner_input_error\n")
                .append(".scanner_signed_return:\n")
                .append("    ret\n\n");
    }

    private static void appendDoubleParser(StringBuilder asm) {
        asm.append("__scanner_parse_double:\n")
                .append("    call __scanner_read_token\n")
                .append("    test rax, rax\n")
                .append("    jz __scanner_input_error\n")
                .append("    mov qword [rel __scanner_double_integer], 0\n")
                .append("    mov qword [rel __scanner_double_fraction], 0\n")
                .append("    mov qword [rel __scanner_double_divisor], 1\n")
                .append("    mov qword [rel __scanner_double_index], 0\n")
                .append("    mov qword [rel __scanner_double_sign], 0\n")
                .append("    mov qword [rel __scanner_double_dot], 0\n")
                .append("    mov qword [rel __scanner_double_digits], 0\n")
                .append("    mov qword [rel __scanner_double_fraction_digits], 0\n")
                .append("    lea rsi, [rel __scanner_token]\n")
                .append("    mov r10, qword [rel __scanner_token_length]\n")
                .append("    xor r9d, r9d\n")
                .append("    mov al, byte [rsi]\n")
                .append("    cmp al, '-'\n")
                .append("    jne .scanner_double_check_plus\n")
                .append("    mov qword [rel __scanner_double_sign], 1\n")
                .append("    inc r9\n")
                .append("    jmp .scanner_double_start\n")
                .append(".scanner_double_check_plus:\n")
                .append("    cmp al, '+'\n")
                .append("    jne .scanner_double_start\n")
                .append("    inc r9\n")
                .append(".scanner_double_start:\n")
                .append("    mov qword [rel __scanner_double_index], r9\n")
                .append("    cmp r9, r10\n")
                .append("    jae __scanner_input_error\n")
                .append(".scanner_double_loop:\n")
                .append("    cmp r9, r10\n")
                .append("    jae .scanner_double_done\n")
                .append("    movzx ecx, byte [rsi + r9]\n")
                .append("    cmp ecx, '.'\n")
                .append("    jne .scanner_double_digit\n")
                .append("    cmp qword [rel __scanner_double_dot], 0\n")
                .append("    jne __scanner_input_error\n")
                .append("    mov qword [rel __scanner_double_dot], 1\n")
                .append("    inc r9\n")
                .append("    jmp .scanner_double_loop\n")
                .append(".scanner_double_digit:\n")
                .append("    sub ecx, '0'\n")
                .append("    cmp ecx, 9\n")
                .append("    ja __scanner_input_error\n")
                .append("    inc qword [rel __scanner_double_digits]\n")
                .append("    cmp qword [rel __scanner_double_dot], 0\n")
                .append("    jne .scanner_double_fraction_digit\n")
                .append("    mov rax, qword [rel __scanner_double_integer]\n")
                .append("    imul rax, rax, 10\n")
                .append("    jo __scanner_input_error\n")
                .append("    add rax, rcx\n")
                .append("    jo __scanner_input_error\n")
                .append("    mov qword [rel __scanner_double_integer], rax\n")
                .append("    jmp .scanner_double_next\n")
                .append(".scanner_double_fraction_digit:\n")
                .append("    cmp qword [rel __scanner_double_fraction_digits], 18\n")
                .append("    jae .scanner_double_next\n")
                .append("    mov rax, qword [rel __scanner_double_fraction]\n")
                .append("    imul rax, rax, 10\n")
                .append("    jo __scanner_input_error\n")
                .append("    add rax, rcx\n")
                .append("    jo __scanner_input_error\n")
                .append("    mov qword [rel __scanner_double_fraction], rax\n")
                .append("    imul rax, qword [rel __scanner_double_divisor], 10\n")
                .append("    jo __scanner_input_error\n")
                .append("    mov qword [rel __scanner_double_divisor], rax\n")
                .append("    inc qword [rel __scanner_double_fraction_digits]\n")
                .append(".scanner_double_next:\n")
                .append("    inc r9\n")
                .append("    jmp .scanner_double_loop\n")
                .append(".scanner_double_done:\n")
                .append("    cmp qword [rel __scanner_double_digits], 0\n")
                .append("    je __scanner_input_error\n")
                .append("    mov rax, qword [rel __scanner_double_integer]\n")
                .append("    cvtsi2sd xmm0, rax\n")
                .append("    mov rax, qword [rel __scanner_double_fraction]\n")
                .append("    cvtsi2sd xmm1, rax\n")
                .append("    mov rax, qword [rel __scanner_double_divisor]\n")
                .append("    cvtsi2sd xmm2, rax\n")
                .append("    divsd xmm1, xmm2\n")
                .append("    addsd xmm0, xmm1\n")
                .append("    cmp qword [rel __scanner_double_sign], 0\n")
                .append("    je .scanner_double_return\n")
                .append("    mov rax, 0x8000000000000000\n")
                .append("    movq xmm3, rax\n")
                .append("    xorpd xmm0, xmm3\n")
                .append(".scanner_double_return:\n")
                .append("    ret\n\n");
    }

