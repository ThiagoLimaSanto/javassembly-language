    private static String method(String owner, String name, String[] parameters, String result) {
        StringBuilder label = new StringBuilder(owner).append('.').append(name).append("__");
        if (parameters.length == 0) {
            label.append("void");
        } else {
            for (int index = 0; index < parameters.length; index++) {
                if (index > 0) label.append("__");
                label.append(mangle(parameters[index]));
            }
        }
        return label.append("__ret_").append(mangle(result)).toString();
    }

    private static String mangle(String type) {
        if (type.equals("String[]")) return "String_array";
        if (type.equals("int") || type.equals("long") || type.equals("double")
                || type.equals("boolean") || type.equals("void")) return type;
        StringBuilder encoded = new StringBuilder("T");
        type.codePoints().forEach(codePoint -> encoded.append('_')
                .append(Integer.toHexString(codePoint)).append('_'));
        return encoded.toString();
    }
