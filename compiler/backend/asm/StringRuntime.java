    static void append(
            StringBuilder asm,
            Map<String, String> stringLabels,
            Map<String, String> stringObjectLabels,
            java.util.List<String> runtimeClassNames) {
        appendStringFunctions(asm, stringLabels);
        appendStringExtras(asm);
        appendUtf8Helpers(asm);
        appendRegexHelpers(asm);
        appendObjectFunctions(asm, stringLabels, runtimeClassNames);
        appendWrapperFunctions(asm, stringObjectLabels);
        appendValueContracts(asm);
        appendStringAllocation(asm, stringLabels);
        appendSignedParser(asm);
        appendDoubleParser(asm);
        appendSignedFormatter(asm);
        appendDoubleFormatter(asm, stringObjectLabels);
    }

